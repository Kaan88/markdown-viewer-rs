#!/usr/bin/env python3
"""Generates crates/core/src/emoji_table.rs from GitHub's gemoji database.

Usage:
    python crates/core/tools/gen_emoji.py path/to/emoji.json > crates/core/src/emoji_table.rs

The JSON is https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json (MIT).
Every alias of every entry with a Unicode `emoji` field becomes (alias, emoji), sorted by
alias bytes so the Rust side can binary search.
"""
import json
import sys


def main():
    with open(sys.argv[1], encoding="utf-8") as f:
        db = json.load(f)
    table = {}
    for entry in db:
        ch = entry.get("emoji")
        if not ch:
            continue
        for alias in entry["aliases"]:
            assert alias not in table, alias
            table[alias] = ch
    out = [
        "// @generated by crates/core/tools/gen_emoji.py from github/gemoji db/emoji.json (MIT).",
        "// Regenerate: python crates/core/tools/gen_emoji.py emoji.json > crates/core/src/emoji_table.rs",
        "// Sorted by byte order of the name; do not edit by hand.",
        "",
        "#[rustfmt::skip]",
        "pub static TABLE: &[(&str, &str)] = &[",
    ]
    for name in sorted(table, key=lambda s: s.encode("utf-8")):
        out.append('    ("%s", "%s"),' % (name, table[name]))
    out.append("];")
    sys.stdout.buffer.write(("\n".join(out) + "\n").encode("utf-8"))


main()
